-- Staging-only first slice. No production rows or MySQL seeds are imported.
-- Keep tinyint flags numeric for compatibility with the existing JSON API.
-- Identity columns permit explicit legacy IDs during a future validated import.

CREATE TABLE temple_node_staging.announcements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 4294967295),
  title varchar(300) NOT NULL,
  body text,
  is_active smallint NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at timestamp(0) without time zone NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE INDEX announcements_active_date ON temple_node_staging.announcements (is_active, created_at);

CREATE TABLE temple_node_staging.sevas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 4294967295),
  name_ta varchar(200) NOT NULL,
  name_en varchar(200) NOT NULL,
  description text,
  amount numeric(10, 2) NOT NULL DEFAULT 0,
  sort_order integer NOT NULL DEFAULT 0,
  is_featured smallint NOT NULL DEFAULT 0 CHECK (is_featured IN (0, 1)),
  is_active smallint NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1))
);
CREATE INDEX sevas_active_sort ON temple_node_staging.sevas (is_active, sort_order);

CREATE TABLE temple_node_staging.events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 4294967295),
  title_ta varchar(300) NOT NULL,
  title_en varchar(300) NOT NULL,
  description text,
  event_date date NOT NULL,
  is_active smallint NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1))
);
CREATE INDEX events_active_date ON temple_node_staging.events (is_active, event_date);

CREATE TABLE temple_node_staging.gallery (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 4294967295),
  filename varchar(255) NOT NULL,
  caption varchar(500),
  is_active smallint NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at timestamp(0) without time zone NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE INDEX gallery_active_date ON temple_node_staging.gallery (is_active, created_at);

CREATE TABLE temple_node_staging.homepage_settings (
  key_name varchar(80) PRIMARY KEY,
  val varchar(10) NOT NULL DEFAULT '1',
  label varchar(300)
);
