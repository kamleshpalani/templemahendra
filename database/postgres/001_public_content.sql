REVOKE ALL ON ALL TABLES IN SCHEMA temple_node_staging FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA temple_node_staging FROM PUBLIC;

DO $$
DECLARE
  browser_role text;
BEGIN
  FOREACH browser_role IN ARRAY ARRAY['anon', 'authenticated']
  LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = browser_role) THEN
      EXECUTE format('REVOKE ALL ON SCHEMA temple_node_staging FROM %I', browser_role);
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA temple_node_staging FROM %I', browser_role);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA temple_node_staging FROM %I', browser_role);
    END IF;
  END LOOP;
END
$$;
